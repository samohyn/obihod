function b2bPage(spec: {
  slug: string
  title: string
  metaTitle: string
  metaDescription: string
  kicker: string
  heroTitle: string
  lead: string
  image: BlockImage
  badge?: { value: string; text: string; note?: string }
  plan: {
    title: string
    text: string
    audiences: { icon: IconName; title: string; text: string }[]
  }
  tiles?: { title: string; items: ServiceTile[] }
  middle?: V3BlockWithTone[]
  sla?: boolean
  faq: { question: string; answer: string }[]
  form: string
}): PageContent {
  const blocks: V3BlockWithTone[] = [
    {
      blockType: 'hero-slider',
      slides: [
        {
          kicker: kicker(spec.kicker),
          title: spec.heroTitle,
          lead: spec.lead,
          primary: { label: 'Запросить расчёт', href: '#zayavka', icon: 'file' },
          secondary: { label: 'Позвонить', href: PHONE_HREF },
          image: spec.image,
        },
      ],
      badge: spec.badge ?? null,
      strip: B2B_STRIP,
    },
    {
      blockType: 'b2b-plan',
      eyebrow: 'Для организаций',
      title: spec.plan.title,
      text: spec.plan.text,
      kpis: [
        { value: '2 ч', label: 'аварийный выезд' },
        { value: '6 ч', label: 'реакция на снегопад' },
        { value: 'ЭДО', label: 'закрывающие документы' },
      ],
      primary: { label: 'Запросить договор', href: '#zayavka' },
      secondary: { label: 'Образец договора', href: '/b2b/dogovor/' },
      audiences: spec.plan.audiences,
      note: {
        title: 'Договор на сезон, год или разово',
        text: 'Фиксированный тариф или цена за объект, график и аварийный режим — в договоре.',
      },
    },
  ]
  if (spec.tiles) {
    blocks.push({
      blockType: 'services-tiles',
      eyebrow: 'Работы',
      title: spec.tiles.title,
      link: { label: 'Все услуги', href: '/uslugi/' },
      items: spec.tiles.items,
    })
  }
  if (spec.sla !== false) blocks.push(SLA)
  blocks.push(...(spec.middle ?? []))
  blocks.push(B2B_STEPS, B2B_DOCS)
  blocks.push({ blockType: 'faq-v3', eyebrow: 'Вопросы', title: 'Частые вопросы', items: spec.faq })
  blocks.push(form('Запросите расчёт — перезвоним за 10 минут', spec.form))
  return {
    slug: spec.slug,
    title: spec.title,
    metaTitle: spec.metaTitle,
    metaDescription: spec.metaDescription,
    blocks: retone(blocks),
  }
}

